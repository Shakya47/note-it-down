import { STORAGE_KEYS, type ConfigureResult, type SyncResult } from '../lib/messages'
import { isStrongToken, normalizeServerUrl, type SyncConfig } from '../sync/config'
import { checkWorker, deleteRemote, sync } from '../sync/sync'
import { getMutationCount, onLocalMutation } from './notesStore'

const PERIODIC_ALARM = 'nid-sync-periodic'
const PERIOD_MINUTES = 5
const AFTER_EDIT_DELAY_MS = 5_000
const OPPORTUNISTIC_THROTTLE_MS = 30_000

let inFlight: Promise<SyncResult> | null = null
let rerunRequested = false
let lastAttemptAt = 0
let debounceTimer: ReturnType<typeof setTimeout> | undefined
let pendingFlagWritten = false

export async function readConfig(): Promise<SyncConfig | null> {
  const result = await chrome.storage.local.get([STORAGE_KEYS.serverUrl, STORAGE_KEYS.token])
  const serverUrl = result[STORAGE_KEYS.serverUrl]
  const token = result[STORAGE_KEYS.token]
  if (typeof serverUrl !== 'string' || typeof token !== 'string' || !serverUrl || !token) return null
  return { serverUrl, token }
}

/** Runs a sync, or joins the one in progress (and runs once more after it). */
export function runSync(): Promise<SyncResult> {
  if (inFlight) {
    rerunRequested = true
    return inFlight
  }
  inFlight = (async () => {
    let result: SyncResult
    do {
      rerunRequested = false
      result = await syncOnce()
    } while (rerunRequested && result.success)
    return result
  })().finally(() => {
    inFlight = null
  })
  return inFlight
}

async function syncOnce(): Promise<SyncResult> {
  const config = await readConfig()
  if (!config) return { success: false, error: 'Sync is not configured' }

  lastAttemptAt = Date.now()
  const mutationsBefore = getMutationCount()
  const result = await sync(config)

  const updates: Record<string, unknown> = {
    [STORAGE_KEYS.lastStatus]: result.success ? 'success' : 'error',
    [STORAGE_KEYS.lastError]: result.error ?? null,
  }
  if (result.success) {
    updates[STORAGE_KEYS.lastSynced] = result.syncedAt
    // Edits made while this sync ran are picked up by the debounce they scheduled.
    if (getMutationCount() === mutationsBefore) {
      updates[STORAGE_KEYS.pending] = false
      pendingFlagWritten = false
    }
  }
  await chrome.storage.local.set(updates)
  return result
}

function scheduleSoon() {
  clearTimeout(debounceTimer)
  debounceTimer = setTimeout(() => void runSync(), AFTER_EDIT_DELAY_MS)
}

/** Called when a drawer opens: pull fresh data unless we synced moments ago. */
export function requestOpportunisticSync() {
  if (Date.now() - lastAttemptAt < OPPORTUNISTIC_THROTTLE_MS) return
  void runSync()
}

export async function ensureAlarm() {
  const existing = await chrome.alarms.get(PERIODIC_ALARM)
  if (!existing) {
    await chrome.alarms.create(PERIODIC_ALARM, { delayInMinutes: 1, periodInMinutes: PERIOD_MINUTES })
  }
}

export function handleAlarm(alarm: chrome.alarms.Alarm) {
  if (alarm.name === PERIODIC_ALARM) void runSync()
}

export function initSyncRunner() {
  onLocalMutation(() => {
    if (!pendingFlagWritten) {
      pendingFlagWritten = true
      void chrome.storage.local.set({ [STORAGE_KEYS.pending]: true })
    }
    scheduleSoon()
  })

  // The service worker may have been stopped with a sync still owed.
  void chrome.storage.local.get(STORAGE_KEYS.pending).then((result) => {
    if (result[STORAGE_KEYS.pending]) {
      pendingFlagWritten = true
      scheduleSoon()
    }
  })
}

async function waitForIdle() {
  while (inFlight) await inFlight.catch(() => undefined)
}

const SYNC_STATE_KEYS = [
  STORAGE_KEYS.syncBase,
  STORAGE_KEYS.lastStatus,
  STORAGE_KEYS.lastError,
  STORAGE_KEYS.lastSynced,
]

export async function configure(serverUrl: string, token: string): Promise<ConfigureResult> {
  const url = normalizeServerUrl(serverUrl)
  const trimmedToken = token.trim()
  if (!isStrongToken(trimmedToken)) {
    throw new Error(
      'Use a token generated by Note It Down: click Generate on your first device, then paste the same token on the others.'
    )
  }
  const worker = await checkWorker(url)

  await waitForIdle()
  const previous = await readConfig()
  if (!previous || previous.serverUrl !== url || previous.token !== trimmedToken) {
    // The last-synced versions belong to the old server/token.
    await chrome.storage.local.remove(SYNC_STATE_KEYS)
  }
  await chrome.storage.local.set({ [STORAGE_KEYS.serverUrl]: url, [STORAGE_KEYS.token]: trimmedToken })

  return { worker, sync: await runSync() }
}

export async function disconnect() {
  await waitForIdle()
  await chrome.storage.local.remove([
    STORAGE_KEYS.serverUrl,
    STORAGE_KEYS.token,
    STORAGE_KEYS.pending,
    ...SYNC_STATE_KEYS,
  ])
  pendingFlagWritten = false
}

/** Deletes this token's data from the worker and disconnects this device. */
export async function deleteRemoteData() {
  const config = await readConfig()
  if (!config) throw new Error('Sync is not configured')
  await waitForIdle()
  await deleteRemote(config)
  await disconnect()
}
